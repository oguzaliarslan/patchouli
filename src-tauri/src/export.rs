//! List export (Taiga `media/anime_list_export.cpp`): Markdown, and
//! MyAnimeList's XML import format.

use std::collections::{BTreeMap, HashMap, HashSet};

use patchouli_core::anime::Type;
use patchouli_core::{Anime, ListEntry, ListStatus, ServiceId};
use patchouli_db::{anime, list, queue};
use serde::Deserialize;
use tauri::State;

use crate::AppState;
use crate::error::{CommandError, CommandResult};

#[derive(Debug, Clone, Copy, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum ExportFormat {
    Markdown,
    MyAnimeListXml,
}

fn status_label(status: ListStatus) -> &'static str {
    match status {
        ListStatus::Watching => "Watching",
        ListStatus::Completed => "Completed",
        ListStatus::OnHold => "On hold",
        ListStatus::Dropped => "Dropped",
        ListStatus::PlanToWatch => "Plan to watch",
        ListStatus::NotInList => "Not in list",
    }
}

/// `# Status` sections with `- Title (watched/total)` lines, sorted by title.
pub fn markdown(entries: &[ListEntry], anime: &HashMap<i32, Anime>) -> String {
    let mut sections: BTreeMap<i32, Vec<String>> = BTreeMap::new();
    for entry in entries {
        let Some(item) = anime.get(&entry.anime_id) else {
            continue;
        };
        sections
            .entry(entry.status as i32)
            .or_default()
            .push(format!(
                "{} ({}/{})",
                item.titles.romaji, entry.watched_episodes, item.episode_count
            ));
    }
    let mut text = String::new();
    for (status, mut lines) in sections {
        lines.sort_by_key(|l| l.to_lowercase());
        if !text.is_empty() {
            text.push('\n');
        }
        let status = ListStatus::from_i32(status).unwrap_or_default();
        text.push_str(&format!("# {}\n\n", status_label(status)));
        for line in lines {
            text.push_str(&format!("- {line}\n"));
        }
    }
    text
}

fn escape(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

fn series_type(kind: Type) -> &'static str {
    match kind {
        Type::Tv => "TV",
        Type::Ova => "OVA",
        Type::Movie => "Movie",
        Type::Special => "Special",
        Type::Ona => "ONA",
        Type::Music => "Music",
        Type::Unknown => "Unknown",
    }
}

fn my_status(status: ListStatus) -> &'static str {
    match status {
        ListStatus::Completed => "Completed",
        ListStatus::OnHold => "On-Hold",
        ListStatus::Dropped => "Dropped",
        ListStatus::PlanToWatch => "Plan to Watch",
        ListStatus::Watching | ListStatus::NotInList => "Watching",
    }
}

/// MyAnimeList's export format, which MAL and other sites can import. IDs are
/// the current service's, as in Taiga, so they're only MAL IDs when synced
/// with MyAnimeList.
pub fn myanimelist_xml(
    entries: &[ListEntry],
    anime: &HashMap<i32, Anime>,
    queued: &HashSet<i32>,
    username: &str,
    generated: &str,
) -> String {
    let entries: Vec<(&ListEntry, &Anime)> = entries
        .iter()
        .filter_map(|e| anime.get(&e.anime_id).map(|a| (e, a)))
        .collect();
    let count = |status| entries.iter().filter(|(e, _)| e.status == status).count();
    let mut xml = String::from("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
    xml.push_str(&format!(
        "<!-- Generated by Patchouli v{} on {generated} -->\n<myanimelist>\n",
        env!("CARGO_PKG_VERSION")
    ));
    xml.push_str("\t<myinfo>\n");
    for (name, value) in [
        ("user_id", "0".to_owned()),
        ("user_name", escape(username)),
        ("user_export_type", "1".to_owned()),
        ("user_total_anime", entries.len().to_string()),
        (
            "user_total_watching",
            count(ListStatus::Watching).to_string(),
        ),
        (
            "user_total_completed",
            count(ListStatus::Completed).to_string(),
        ),
        ("user_total_onhold", count(ListStatus::OnHold).to_string()),
        ("user_total_dropped", count(ListStatus::Dropped).to_string()),
        (
            "user_total_plantowatch",
            count(ListStatus::PlanToWatch).to_string(),
        ),
    ] {
        xml.push_str(&format!("\t\t<{name}>{value}</{name}>\n"));
    }
    xml.push_str("\t</myinfo>\n");
    for (entry, item) in entries {
        xml.push_str("\t<anime>\n");
        let fields = [
            ("series_animedb_id", item.id.to_string()),
            ("series_title", escape(&item.titles.romaji)),
            ("series_type", series_type(item.r#type).to_owned()),
            ("series_episodes", item.episode_count.max(0).to_string()),
            ("my_id", "0".to_owned()),
            ("my_watched_episodes", entry.watched_episodes.to_string()),
            ("my_start_date", entry.date_started.to_string()),
            ("my_finish_date", entry.date_completed.to_string()),
            ("my_fansub_group", String::new()),
            ("my_rated", String::new()),
            (
                "my_score",
                (entry.score * 10 / patchouli_core::list::SCORE_MAX).to_string(),
            ),
            ("my_dvd", String::new()),
            ("my_storage", String::new()),
            ("my_status", my_status(entry.status).to_owned()),
            ("my_comments", escape(&entry.notes)),
            ("my_times_watched", entry.rewatched_times.to_string()),
            ("my_rewatch_value", String::new()),
            ("my_downloaded_eps", "0".to_owned()),
            ("my_tags", String::new()),
            ("my_rewatching", i32::from(entry.rewatching).to_string()),
            ("my_rewatching_ep", entry.rewatching_ep.to_string()),
            (
                "update_on_import",
                i32::from(queued.contains(&entry.anime_id)).to_string(),
            ),
        ];
        for (name, value) in fields {
            xml.push_str(&format!("\t\t<{name}>{value}</{name}>\n"));
        }
        xml.push_str("\t</anime>\n");
    }
    xml.push_str("</myanimelist>\n");
    xml
}

/// Writes the list to `path` in `format`.
#[tauri::command]
pub fn list_export(
    state: State<'_, AppState>,
    format: ExportFormat,
    path: String,
) -> CommandResult<usize> {
    let (entries, items, queued) = {
        let db = state.db.lock()?;
        let entries: Vec<ListEntry> = list::all(&db)?
            .into_iter()
            .filter(|e| !e.pending_delete)
            .collect();
        let items: HashMap<i32, Anime> = anime::all(&db)?.into_iter().map(|a| (a.id, a)).collect();
        let queued: HashSet<i32> = queue::all(&db)?.iter().map(|q| q.anime_id).collect();
        (entries, items, queued)
    };
    let text = match format {
        ExportFormat::Markdown => markdown(&entries, &items),
        ExportFormat::MyAnimeListXml => {
            let username = state
                .accounts
                .get(ServiceId::MyAnimeList)
                .map(|a| a.username)
                .unwrap_or_default();
            let generated = chrono::Utc::now().format("%Y-%m-%dT%H:%M:%SZ").to_string();
            myanimelist_xml(&entries, &items, &queued, &username, &generated)
        }
    };
    std::fs::write(&path, text)
        .map_err(|e| CommandError::new(format!("Couldn't write {path}: {e}")))?;
    log::info!("Exported {} entries to {path}", entries.len());
    Ok(entries.len())
}

#[cfg(test)]
mod tests {
    use patchouli_core::FuzzyDate;
    use patchouli_core::anime::Titles;

    use super::*;

    fn data() -> (Vec<ListEntry>, HashMap<i32, Anime>) {
        let anime = |id, title: &str, episodes| Anime {
            id,
            episode_count: episodes,
            r#type: Type::Tv,
            titles: Titles {
                romaji: title.into(),
                ..Titles::default()
            },
            ..Anime::default()
        };
        let entry = |id, watched, status, score| ListEntry {
            anime_id: id,
            watched_episodes: watched,
            status,
            score,
            date_started: FuzzyDate::new(2024, 1, 0),
            ..ListEntry::default()
        };
        (
            vec![
                entry(1, 12, ListStatus::Completed, 85),
                entry(2, 3, ListStatus::Watching, 0),
                entry(3, 1, ListStatus::Watching, 0),
                entry(99, 1, ListStatus::Watching, 0), // no anime data: skipped
            ],
            [
                anime(1, "Toradora!", 25),
                anime(2, "Zetman", 13),
                anime(3, "Akira & <Co>", 1),
            ]
            .into_iter()
            .map(|a| (a.id, a))
            .collect(),
        )
    }

    #[test]
    fn markdown_groups_by_status() {
        let (entries, anime) = data();
        assert_eq!(
            markdown(&entries, &anime),
            "# Watching\n\n- Akira & <Co> (1/1)\n- Zetman (3/13)\n\n# Completed\n\n- Toradora! (12/25)\n"
        );
    }

    #[test]
    fn myanimelist_xml_format() {
        let (entries, anime) = data();
        let queued = HashSet::from([2]);
        let xml = myanimelist_xml(&entries, &anime, &queued, "me", "2026-01-01T00:00:00Z");
        assert!(xml.starts_with("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"));
        assert!(xml.contains("<user_total_anime>3</user_total_anime>"));
        assert!(xml.contains("<user_total_watching>2</user_total_watching>"));
        assert!(xml.contains("<series_title>Akira &amp; &lt;Co&gt;</series_title>"));
        assert!(xml.contains("<my_score>8</my_score>"));
        assert!(xml.contains("<my_status>Completed</my_status>"));
        assert!(xml.contains("<my_start_date>2024-01-00</my_start_date>"));
        assert_eq!(
            xml.matches("<update_on_import>1</update_on_import>")
                .count(),
            1
        );
        assert_eq!(xml.matches("<anime>").count(), 3);
    }
}
